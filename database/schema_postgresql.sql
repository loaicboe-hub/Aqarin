CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "postgis";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";

-- Automated Timestamp Update Trigger
CREATE OR REPLACE FUNCTION trigger_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 1. Users Table
DO $$ BEGIN
  CREATE TYPE user_role_enum AS ENUM ('buyer', 'seller', 'agent', 'admin', 'super_admin');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  phone VARCHAR(30) NULL,
  role user_role_enum NOT NULL DEFAULT 'buyer',
  avatar VARCHAR(255) NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

-- 2. Location Benchmarks Table
CREATE TABLE IF NOT EXISTS location_benchmarks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city_en VARCHAR(100) NOT NULL,
  city_ar VARCHAR(100) NOT NULL,
  district_en VARCHAR(100) NOT NULL,
  district_ar VARCHAR(100) NOT NULL,
  compound_en VARCHAR(150) NULL,
  compound_ar VARCHAR(150) NULL,
  avg_price_sqm NUMERIC(12, 2) NOT NULL,
  min_price_sqm NUMERIC(12, 2) NOT NULL,
  max_price_sqm NUMERIC(12, 2) NOT NULL,
  rental_yield_pct NUMERIC(5, 2) NOT NULL DEFAULT 7.50,
  annual_growth_pct NUMERIC(5, 2) NOT NULL DEFAULT 18.00,
  lat NUMERIC(10, 7) NOT NULL,
  lng NUMERIC(10, 7) NOT NULL,
  location_geog GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (
    CASE WHEN lat IS NOT NULL AND lng IS NOT NULL 
         THEN ST_SetSRID(ST_MakePoint(lng, lat), 4326)::geography 
         ELSE NULL 
    END
  ) STORED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_benchmarks_lat CHECK (lat >= -90.0 AND lat <= 90.0),
  CONSTRAINT chk_benchmarks_lng CHECK (lng >= -180.0 AND lng <= 180.0)
);

CREATE INDEX IF NOT EXISTS idx_benchmarks_city ON location_benchmarks(city_en);
CREATE INDEX IF NOT EXISTS idx_benchmarks_district ON location_benchmarks(district_en);
CREATE INDEX IF NOT EXISTS idx_benchmarks_geog ON location_benchmarks USING GIST(location_geog);

-- 3. Properties Table
DO $$ BEGIN
  CREATE TYPE property_purpose_enum AS ENUM ('sale', 'rent');
EXCEPTION WHEN duplicate_object THEN null; END $$;

DO $$ BEGIN
  CREATE TYPE property_category_enum AS ENUM ('residential', 'commercial');
EXCEPTION WHEN duplicate_object THEN null; END $$;

DO $$ BEGIN
  CREATE TYPE property_status_enum AS ENUM ('published', 'pending_review', 'rejected', 'archived');
EXCEPTION WHEN duplicate_object THEN null; END $$;

DO $$ BEGIN
  CREATE TYPE property_finishing_enum AS ENUM ('core_shell', 'semi_finished', 'fully_finished', 'ultra_lux');
EXCEPTION WHEN duplicate_object THEN null; END $$;

CREATE TABLE IF NOT EXISTS properties (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_en VARCHAR(255) NOT NULL,
  title_ar VARCHAR(255) NOT NULL,
  description_en TEXT NULL,
  description_ar TEXT NULL,
  purpose property_purpose_enum NOT NULL DEFAULT 'sale',
  category property_category_enum NOT NULL DEFAULT 'residential',
  property_type VARCHAR(50) NOT NULL,
  price NUMERIC(14, 2) NOT NULL,
  area_sqm INTEGER NOT NULL,
  bedrooms INTEGER NOT NULL DEFAULT 0,
  bathrooms INTEGER NOT NULL DEFAULT 0,
  floor_level INTEGER NOT NULL DEFAULT 1,
  finishing_type property_finishing_enum NOT NULL DEFAULT 'fully_finished',
  delivery_status VARCHAR(50) NOT NULL DEFAULT 'ready',
  delivery_year INTEGER NOT NULL DEFAULT 2026,
  payment_type VARCHAR(50) NOT NULL DEFAULT 'installments',
  down_payment NUMERIC(14, 2) NOT NULL DEFAULT 0,
  installment_years INTEGER NOT NULL DEFAULT 0,
  monthly_installment NUMERIC(12, 2) NOT NULL DEFAULT 0,
  city VARCHAR(100) NOT NULL,
  district VARCHAR(100) NOT NULL,
  compound VARCHAR(150) NULL,
  address VARCHAR(255) NULL,
  lat NUMERIC(10, 7) NOT NULL,
  lng NUMERIC(10, 7) NOT NULL,
  location_geog GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (
    CASE WHEN lat IS NOT NULL AND lng IS NOT NULL 
         THEN ST_SetSRID(ST_MakePoint(lng, lat), 4326)::geography 
         ELSE NULL 
    END
  ) STORED,
  aqar_score NUMERIC(3, 1) NOT NULL DEFAULT 8.8,
  images_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  amenities_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  status property_status_enum NOT NULL DEFAULT 'published',
  user_id INTEGER NULL REFERENCES users(id) ON DELETE SET NULL,
  views_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_prop_lat CHECK (lat >= -90.0 AND lat <= 90.0),
  CONSTRAINT chk_prop_lng CHECK (lng >= -180.0 AND lng <= 180.0),
  CONSTRAINT chk_prop_price CHECK (price > 0),
  CONSTRAINT chk_prop_area CHECK (area_sqm > 0)
);

CREATE INDEX IF NOT EXISTS idx_prop_purpose ON properties(purpose);
CREATE INDEX IF NOT EXISTS idx_prop_category ON properties(category);
CREATE INDEX IF NOT EXISTS idx_prop_city ON properties(city);
CREATE INDEX IF NOT EXISTS idx_prop_price ON properties(price);
CREATE INDEX IF NOT EXISTS idx_prop_score ON properties(aqar_score DESC);
CREATE INDEX IF NOT EXISTS idx_prop_amenities ON properties USING GIN(amenities_json);
CREATE INDEX IF NOT EXISTS idx_prop_geog ON properties USING GIST(location_geog);

DROP TRIGGER IF EXISTS trg_properties_updated_at ON properties;
CREATE TRIGGER trg_properties_updated_at
BEFORE UPDATE ON properties
FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

-- 4. Property Leads & Inquiries Table
